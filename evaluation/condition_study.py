"""Tilt/condition experiment framework.

The manifest supplies a *measured* tilt angle per captured frame. Grouping is
always by that measured angle; a ``target_angle_deg`` column may be kept for
provenance but is never treated as a measurement. System results are saved
inference JSON files, and error is only computed where a manual ground-truth
row exists.

No angle, measurement or ground-truth value is generated by this module.
"""

from __future__ import annotations

import argparse
import math
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Sequence

from evaluation.common import (
    EvaluationError,
    GroundTruth,
    ResultView,
    error_summary,
    fmt,
    image_present,
    load_ground_truth,
    md_table,
    parse_float,
    read_csv,
    read_result,
    utc_now,
    write_csv,
    write_json,
    write_markdown,
)

STUDY_SCHEMA = "measureit.condition_study/1"


def load_angle_manifest(path: str | Path) -> list[dict[str, Any]]:
    rows = read_csv(
        path,
        required=("stem",),
        optional=(
            "measured_angle_deg",
            "angle_deg",
            "target_angle_deg",
            "condition",
            "notes",
        ),
        what="tilt manifest",
    )
    if not rows:
        raise EvaluationError("tilt manifest has no instances")

    manifest: list[dict[str, Any]] = []
    seen: set[str] = set()
    for line_number, row in enumerate(rows, start=2):
        stem = row["stem"]
        if not stem:
            raise EvaluationError(f"tilt manifest row {line_number}: stem is empty")
        if stem in seen:
            raise EvaluationError(f"tilt manifest repeats stem {stem!r}")
        seen.add(stem)

        measured_text = row.get("measured_angle_deg", "")
        alias_text = row.get("angle_deg", "")
        if measured_text and alias_text:
            measured = parse_float(
                measured_text,
                f"measured_angle_deg for {stem}",
                minimum=0.0,
                maximum=90.0,
            )
            alias = parse_float(
                alias_text,
                f"angle_deg for {stem}",
                minimum=0.0,
                maximum=90.0,
            )
            if not math.isclose(measured, alias, abs_tol=1e-9):
                raise EvaluationError(
                    f"{stem}: measured_angle_deg ({measured}) and angle_deg "
                    f"({alias}) disagree; keep one measured value"
                )
            angle = measured
        elif measured_text:
            angle = parse_float(
                measured_text,
                f"measured_angle_deg for {stem}",
                minimum=0.0,
                maximum=90.0,
            )
        elif alias_text:
            angle = parse_float(
                alias_text,
                f"angle_deg for {stem}",
                minimum=0.0,
                maximum=90.0,
            )
        elif row.get("target_angle_deg", ""):
            raise EvaluationError(
                f"{stem}: only target_angle_deg is present. Record the measured "
                "tilt angle in measured_angle_deg (or angle_deg); a target is "
                "not a measurement."
            )
        else:
            raise EvaluationError(
                f"{stem}: measured tilt angle is missing; add measured_angle_deg "
                "(or angle_deg)"
            )

        target = None
        if row.get("target_angle_deg", ""):
            target = parse_float(
                row["target_angle_deg"],
                f"target_angle_deg for {stem}",
                minimum=0.0,
                maximum=90.0,
            )
        manifest.append(
            {
                "stem": stem,
                "angle_deg": angle,
                "target_angle_deg": target,
                "condition": row.get("condition", ""),
                "notes": row.get("notes", ""),
            }
        )
    return manifest


def _instance(
    row: dict[str, Any],
    view: ResultView,
    truth: GroundTruth | None,
    *,
    images_dir: Path | None,
) -> dict[str, Any]:
    width_error = height_error = None
    width_abs = height_abs = None
    width_pct = height_pct = None
    if view.ok and truth is not None:
        width_error = float(view.width_mm) - truth.width_mm
        height_error = float(view.height_mm) - truth.height_mm
        width_abs = abs(width_error)
        height_abs = abs(height_error)
        width_pct = 100.0 * width_abs / truth.width_mm
        height_pct = 100.0 * height_abs / truth.height_mm

    return {
        "stem": row["stem"],
        "angle_deg": row["angle_deg"],
        "target_angle_deg": row["target_angle_deg"],
        "condition": row["condition"],
        "notes": row["notes"],
        "image_present": image_present(images_dir, row["stem"]),
        "result_path": None if view.result_path is None else str(view.result_path),
        "status": view.status,
        "code": view.code,
        "message": view.message,
        "reliability": view.reliability,
        "width_mm": view.width_mm,
        "height_mm": view.height_mm,
        "ground_truth_present": truth is not None,
        "truth_width_mm": None if truth is None else truth.width_mm,
        "truth_height_mm": None if truth is None else truth.height_mm,
        "instrument": None if truth is None else truth.instrument,
        "width_error_mm": width_error,
        "height_error_mm": height_error,
        "width_abs_error_mm": width_abs,
        "height_abs_error_mm": height_abs,
        "width_error_pct": width_pct,
        "height_error_pct": height_pct,
    }


def _error_metrics(
    instances: Sequence[dict[str, Any]], *, truth_supplied: bool
) -> dict[str, Any]:
    pairs = [
        instance
        for instance in instances
        if instance["width_error_mm"] is not None
        and instance["height_error_mm"] is not None
    ]
    if not pairs:
        reason = (
            "no successful measurement has a matching ground-truth row"
            if truth_supplied
            else "no ground-truth measurements were supplied"
        )
        return {
            "available": False,
            "reason": reason,
            "n_pairs": 0,
            "width": error_summary([], []),
            "height": error_summary([], []),
            "combined": error_summary([], []),
        }

    width_errors = [float(instance["width_error_mm"]) for instance in pairs]
    height_errors = [float(instance["height_error_mm"]) for instance in pairs]
    width_truth = [float(instance["truth_width_mm"]) for instance in pairs]
    height_truth = [float(instance["truth_height_mm"]) for instance in pairs]
    return {
        "available": True,
        "reason": None,
        "n_pairs": len(pairs),
        "width": error_summary(width_errors, width_truth),
        "height": error_summary(height_errors, height_truth),
        "combined": error_summary(
            width_errors + height_errors, width_truth + height_truth
        ),
    }


def _group_metrics(
    instances: Sequence[dict[str, Any]], *, truth_supplied: bool
) -> dict[str, Any]:
    failed = [
        instance
        for instance in instances
        if instance["code"] not in {"ok", "low_reliability"}
    ]
    codes = Counter(instance["code"] for instance in instances)
    return {
        "n_instances": len(instances),
        "n_ok": len(instances) - len(failed),
        "n_failed": len(failed),
        "failure_rate_pct": 100.0 * len(failed) / len(instances),
        "codes": dict(sorted(codes.items())),
        "error_metrics": _error_metrics(instances, truth_supplied=truth_supplied),
    }


def _csv_value(value: Any) -> Any:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.6f}"
    return value


def build_condition_study(
    *,
    manifest_path: str | Path,
    results_dir: str | Path,
    out_dir: str | Path,
    ground_truth_path: str | Path | None = None,
    images_dir: str | Path | None = None,
) -> dict[str, Any]:
    manifest = load_angle_manifest(manifest_path)
    results_path = Path(results_dir)
    images_path = None if images_dir is None else Path(images_dir)

    truth: dict[str, GroundTruth] | None = None
    truth_error = None
    if ground_truth_path is not None:
        truth_path = Path(ground_truth_path)
        if not truth_path.is_file():
            truth_error = f"ground-truth CSV not found: {truth_path}"
        else:
            truth = load_ground_truth(truth_path)

    instances = [
        _instance(
            row,
            read_result(results_path, row["stem"]),
            None if truth is None else truth.get(row["stem"]),
            images_dir=images_path,
        )
        for row in manifest
    ]

    grouped: dict[float, list[dict[str, Any]]] = {}
    for instance in instances:
        grouped.setdefault(float(instance["angle_deg"]), []).append(instance)

    groups = [
        {
            "angle_deg": angle,
            **_group_metrics(grouped[angle], truth_supplied=truth is not None),
        }
        for angle in sorted(grouped)
    ]
    overall = _group_metrics(instances, truth_supplied=truth is not None)
    results_available = any(instance["result_path"] is not None for instance in instances)

    if not results_available:
        status = "unavailable"
        code = "missing_results"
        message = (
            f"no saved inference results were found for the manifest stems in "
            f"{results_path}"
        )
    elif truth is None:
        status = "partial"
        code = "ground_truth_unavailable"
        message = truth_error or (
            "no ground-truth CSV was supplied; failure rate is available but "
            "no error metric can be computed"
        )
    elif not overall["error_metrics"]["available"]:
        status = "partial"
        code = "no_ground_truth_pairs"
        message = overall["error_metrics"]["reason"]
    else:
        status = "ok"
        code = None
        message = "condition study computed from saved results and ground truth"

    missing_truth = [
        instance["stem"] for instance in instances if not instance["ground_truth_present"]
    ]
    payload = {
        "schema": STUDY_SCHEMA,
        "created_utc": utc_now(),
        "status": status,
        "code": code,
        "message": message,
        "manifest": str(Path(manifest_path)),
        "results_dir": str(results_path),
        "ground_truth": None if ground_truth_path is None else str(Path(ground_truth_path)),
        "ground_truth_error": truth_error,
        "images_dir": None if images_path is None else str(images_path),
        "results_available": results_available,
        "angle_source": "measured_angle_deg (or angle_deg); target_angle_deg is informational only",
        "instances": instances,
        "groups": groups,
        "overall": overall,
        "missing_ground_truth_stems": missing_truth,
        "notes": [
            "grouping uses the measured tilt angle supplied in the manifest; "
            "a target angle is never substituted for a measurement",
            "errors are system minus manually measured ground truth in millimetres",
            "failure includes missing results and every non-ok inference status",
            "synthetic test fixtures, if any, are software checks and not "
            "real-world accuracy evidence",
        ],
    }

    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    payload["report_paths"] = {
        "json": str(out_path / "condition_study.json"),
        "csv": str(out_path / "condition_study.csv"),
        "markdown": str(out_path / "condition_study.md"),
    }
    write_json(out_path / "condition_study.json", payload)
    header = [
        "stem",
        "angle_deg",
        "target_angle_deg",
        "condition",
        "status",
        "code",
        "reliability",
        "width_mm",
        "height_mm",
        "truth_width_mm",
        "truth_height_mm",
        "width_error_mm",
        "height_error_mm",
        "width_abs_error_mm",
        "height_abs_error_mm",
        "width_error_pct",
        "height_error_pct",
        "image_present",
        "result_path",
        "notes",
    ]
    write_csv(
        out_path / "condition_study.csv",
        header,
        [
            [_csv_value(instance[name]) for name in header]
            for instance in instances
        ],
    )

    lines = [
        "# Tilt / condition study",
        "",
        f"- Generated: {payload['created_utc']}",
        f"- Manifest: `{payload['manifest']}`",
        f"- Results: `{payload['results_dir']}`",
        f"- Ground truth: `{payload['ground_truth'] or 'not supplied'}`",
        f"- Images: `{payload['images_dir'] or 'not supplied'}`",
        f"- Status: **{status}**" + ("" if code is None else f" (`{code}`)"),
        f"- Instances: {overall['n_instances']}; ok: {overall['n_ok']}; "
        f"failed: {overall['n_failed']}; failure rate: "
        f"{fmt(overall['failure_rate_pct'], 2)} %",
        "",
        "## Angle provenance",
        "",
        "Grouping uses the measured angle from `measured_angle_deg` or "
        "`angle_deg`. A `target_angle_deg` column is shown for provenance but "
        "is never used as a measurement. If no measured angle is present, the "
        "tool refuses rather than substituting the target.",
        "",
        "## By measured angle",
        "",
    ]
    rows = []
    for group in groups:
        metrics = group["error_metrics"]
        width_metrics = metrics["width"]
        height_metrics = metrics["height"]
        combined = metrics["combined"]
        rows.append(
            [
                fmt(group["angle_deg"], 2),
                group["n_instances"],
                group["n_ok"],
                group["n_failed"],
                fmt(group["failure_rate_pct"], 2),
                fmt(width_metrics["mae_mm"], 3),
                fmt(height_metrics["mae_mm"], 3),
                fmt(combined["max_abs_error_mm"], 3),
                fmt(combined["mean_percentage_error_pct"], 3),
            ]
        )
    lines.extend(
        md_table(
            [
                "angle (deg)",
                "n",
                "ok",
                "failed",
                "failure %",
                "MAE width (mm)",
                "MAE height (mm)",
                "max abs (mm)",
                "mean % error",
            ],
            rows,
        )
    )
    if not overall["error_metrics"]["available"]:
        lines.extend(
            [
                "",
                f"Error metrics unavailable: {overall['error_metrics']['reason']}.",
            ]
        )

    lines.extend(["", "## Per instance", ""])
    instance_rows = []
    for instance in instances:
        system = (
            "—"
            if instance["width_mm"] is None
            else f"{instance['width_mm']:.2f} x {instance['height_mm']:.2f}"
        )
        truth_text = (
            "—"
            if instance["truth_width_mm"] is None
            else f"{instance['truth_width_mm']:.2f} x {instance['truth_height_mm']:.2f}"
        )
        errors = (
            "—"
            if instance["width_abs_error_mm"] is None
            else f"{instance['width_abs_error_mm']:.2f} / "
            f"{instance['height_abs_error_mm']:.2f}"
        )
        instance_rows.append(
            [
                instance["stem"],
                fmt(instance["angle_deg"], 2),
                instance["status"],
                instance["code"],
                system,
                truth_text,
                errors,
                instance["reliability"] or "—",
            ]
        )
    lines.extend(
        md_table(
            [
                "stem",
                "angle (deg)",
                "status",
                "code",
                "system (mm)",
                "truth (mm)",
                "abs error w/h (mm)",
                "reliability",
            ],
            instance_rows,
        )
    )

    lines.extend(["", "## Coverage", ""])
    if missing_truth:
        lines.append(
            f"- {len(missing_truth)} of {len(instances)} instance(s) have no "
            f"ground-truth row: {', '.join(missing_truth[:20])}"
            + (" ..." if len(missing_truth) > 20 else "")
        )
    else:
        lines.append("- Every instance has a ground-truth row.")
    if truth_error:
        lines.append(f"- Ground truth error: {truth_error}")
    lines.extend(
        [
            "",
            "## Scope",
            "",
            "This report is an analysis of saved software outputs. It does not "
            "capture images, measure ground truth, or create tilt angles. A "
            "synthetic fixture is not real-world evidence.",
            "",
        ]
    )
    write_markdown(out_path / "condition_study.md", lines)
    return payload


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m evaluation.condition_study",
        description="Group saved measurements by measured tilt angle and report "
        "error and failure rate. Never invents angles or ground truth.",
    )
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--results", required=True, type=Path)
    parser.add_argument("--ground-truth", type=Path, default=None)
    parser.add_argument("--images", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=Path("results/condition_study"))
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        payload = build_condition_study(
            manifest_path=args.manifest,
            results_dir=args.results,
            ground_truth_path=args.ground_truth,
            images_dir=args.images,
            out_dir=args.out,
        )
    except EvaluationError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    print(
        f"{payload['status'].upper()}: {payload['overall']['n_instances']} "
        f"instance(s), {len(payload['groups'])} angle group(s), "
        f"failure rate {payload['overall']['failure_rate_pct']:.2f}%"
    )
    if not payload["overall"]["error_metrics"]["available"]:
        print(f"error metrics unavailable: {payload['overall']['error_metrics']['reason']}")
    print(f"json: {args.out / 'condition_study.json'}")
    print(f"csv: {args.out / 'condition_study.csv'}")
    print(f"markdown: {args.out / 'condition_study.md'}")
    return 0 if payload["status"] in {"ok", "partial"} else 3


if __name__ == "__main__":
    raise SystemExit(main())
